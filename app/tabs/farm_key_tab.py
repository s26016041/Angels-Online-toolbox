"""自動掛機（按鍵）分頁。

跟「自動掛機」完全一樣，只差**怎麼出手**：

    自動掛機        選定封包 → 之後一直送「動作 + 施放」封包
    自動掛機（按鍵） 選定封包 → 之後**狂按技能鍵**（F1~F12，由使用者選）

為什麼要兩種
------------
封包攻擊快，但施放是我們自己算距離、自己走過去的；按鍵攻擊則是把判斷交還給
遊戲客戶端 —— 客戶端知道每個技能真正的射程，會自己走到打得到的位置再出手。
近戰角色（實測雪狐）用按鍵比較穩，遠程角色（實測黑狐）用封包比較快。

★ 選怪還是用封包：我們是直接寫記憶體選目標的，遊戲不會自己送「選定」那一包，
  所以兩種模式都會補送一次（換目標時送，不必每次攻擊都送）。

★ 這裡**只設三個類別屬性，不複製任何邏輯**。兩個分頁共用 farm_tab.py 的
  CharFarmPage / KeyWorker / TargetWorker —— 複製一份程式碼的話，
  修好的 bug 只會修到其中一邊。

設定各自獨立（前綴 farmkey），跟「自動掛機」那邊互不影響。
"""
from __future__ import annotations

from app.tabs.farm_tab import MODE_KEY, FarmTab


class FarmKeyTab(FarmTab):
    TAB_TITLE = "自動練功按鍵"
    ORDER = 6                      # 排在「自動掛機」後面
    ATTACK_MODE = MODE_KEY
    SETTINGS_PREFIX = "farmkey"    # ⚠ 一定要跟 FarmTab 不同，否則設定會互相覆蓋
    HINT_ATTACK = ("會挑**離自己最近**的一隻，用封包選定牠、"
                   "然後持續送技能鍵讓遊戲自己出手（射程與走位交給客戶端判斷）；")
